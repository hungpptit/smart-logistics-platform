export async function seedTrafficCameras() {
  console.log(`📷 Đang nạp ${HCMC_TRAFFIC_CAMERAS.length} điểm Camera phạt nguội tại TP.HCM...`);

  let createdCount = 0;
  for (const cam of HCMC_TRAFFIC_CAMERAS) {
    await prisma.trafficCamera.upsert({
      where: { code: cam.code },
      update: {
        name: cam.name,
        address: cam.address,
        latitude: cam.latitude,
        longitude: cam.longitude,
        warningDistance: cam.warningDistance,
        bearing: cam.bearing,
        district: cam.district,
        city: cam.city,
        isActive: cam.isActive,
      },
      create: cam,
    });
    createdCount++;
  }

  console.log(`✅ Đã nạp thành công ${createdCount} camera phạt nguội vào database!`);
}

// Cho phép chạy trực tiếp qua lệnh ts-node
if (require.main === module) {
  seedTrafficCameras()
    .catch((e) => {
      console.error('❌ Lỗi khi seed camera:', e);
      process.exit(1);
    })
    .finally(async () => {
      await prisma.$disconnect();
    });
}
